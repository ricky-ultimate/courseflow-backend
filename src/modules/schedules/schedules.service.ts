  async toggleFixed(
    id: string,
    requestingUser: { id: string; role: string },
  ): Promise<Schedule> {
    const schedule = await this.prisma.schedule.findUnique({
      where: { id },
      include: {
        course: {
          include: {
            department: true,
            lecturer: { select: { id: true, name: true, email: true } },
          },
        },
      },
    });

    if (!schedule) {
      throw new NotFoundException(`Schedule '${id}' not found`);
    }

    if (requestingUser.role === Role.HOD) {
      const hodUser = await this.prisma.user.findUnique({
        where: { id: requestingUser.id },
        include: { managedDepartment: true },
      });

      if (!hodUser?.managedDepartment) {
        throw new ForbiddenException('HOD must be assigned to a department');
      }

      if (schedule.course.departmentCode !== hodUser.managedDepartment.code) {
        throw new ForbiddenException(
          'HODs can only pin or unpin schedules in their own department',
        );
      }
    }

    return this.prisma.schedule.update({
      where: { id },
      data: { isFixed: !schedule.isFixed },
      include: {
        course: {
          include: {
            department: true,
            lecturer: { select: { id: true, name: true, email: true } },
          },
        },
      },
    });
  }

  private async resolveLockedDepartmentCodes(
    departmentCode: string | null,
  ): Promise<string[]> {
    if (departmentCode !== null) {
      return [];
    }

    const lockedDepts = await this.prisma.department.findMany({
      where: { isScheduleLocked: true, isActive: true },
      select: { code: true },
    });

    return lockedDepts.map((d) => d.code);
  }

  private validateTimeSlot(
    startTime: string,
    endTime: string,
    dayOfWeek?: DayOfWeek,
  ): void {
    if (dayOfWeek === DayOfWeek.SATURDAY || dayOfWeek === DayOfWeek.SUNDAY) {
      throw new BadRequestException('Weekend classes are not allowed');
    }

    const [startHour, startMin] = startTime.split(':').map(Number);
    const [endHour, endMin] = endTime.split(':').map(Number);

    if (startMin !== 0 || endMin !== 0) {
      throw new BadRequestException(
        'Class times must be on the hour (e.g. 09:00, 11:00)',
      );
    }

    const duration = endHour - startHour;

    if (duration < 1) {
      throw new BadRequestException('End time must be after start time');
    }

    if (startHour < 9 || endHour > 19) {
      throw new BadRequestException('Classes must run between 09:00 and 19:00');
    }

    if (dayOfWeek === DayOfWeek.WEDNESDAY && endHour > 15) {
      throw new BadRequestException('Wednesday classes must end by 15:00');
    }
  }

  private async checkUniversityCourseClash(
    courseLevel: Level,
    dayOfWeek: DayOfWeek,
    startTime: string,
    endTime: string,
    sessionId: string,
    excludeScheduleId?: string,
  ): Promise<void> {
    const fixedUniversitySchedules = await this.prisma.schedule.findMany({
      where: {
        sessionId,
        dayOfWeek,
        isFixed: true,
        ...(excludeScheduleId && { id: { not: excludeScheduleId } }),
        course: {
          isGeneral: true,
          level: courseLevel,
        },
      },
      include: {
        course: { select: { code: true, name: true } },
      },
    });

    if (fixedUniversitySchedules.length === 0) return;

    const candidateStart = this.timeToMinutes(startTime);
    const candidateEnd = this.timeToMinutes(endTime);

    for (const fixed of fixedUniversitySchedules) {
      const fixedStart = this.timeToMinutes(fixed.startTime);
      const fixedEnd = this.timeToMinutes(fixed.endTime);

      const overlaps = candidateStart < fixedEnd && fixedStart < candidateEnd;

      if (overlaps) {
        throw new ConflictException(
          `Time slot ${startTime}-${endTime} on ${dayOfWeek} conflicts with university course ` +
            `${fixed.course.code} (${fixed.course.name}) fixed at ${fixed.startTime}-${fixed.endTime}. ` +
            `All ${courseLevel} courses must avoid this window.`,
        );
      }
    }
  }

  private timeToMinutes(time: string): number {
    const [hours, minutes] = time.split(':').map(Number);
    return hours * 60 + minutes;
  }
